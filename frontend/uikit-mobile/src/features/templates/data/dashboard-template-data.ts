export const DASHBOARD_TEMPLATES: readonly DashboardTemplate[] = inputs.map(
  ([id, title, family, group, kind, webPath, description]) => ({
    id,
    title,
    family,
    group,
    kind,
    webPath,
    description,
    keywords: [id, title, family, group, kind, webPath],
  }),
);

const sectionCopy: Readonly<
  Record<DashboardTemplateGroup, { title: string; description: string }>
> = {
  overview: {
    title: 'Overview dashboards',
    description: 'Six complete executive and operational overview layouts.',
  },
  management: {
    title: 'Management flows',
    description: 'List, detail, create, edit and account templates.',
  },
  workspace: {
    title: 'Workspace tools',
    description: 'Files, mail, chat, calendar and kanban.',
  },
  system: {
    title: 'System pages',
    description: 'Permission-aware and blank authenticated surfaces.',
  },
};

export const DASHBOARD_TEMPLATE_SECTIONS: readonly DashboardTemplateSection[] =
  (['overview', 'management', 'workspace', 'system'] as const).map(id => ({
    id,
    ...sectionCopy[id],
    templates: DASHBOARD_TEMPLATES.filter(template => template.group === id),
  }));

export const getDashboardTemplate = (
  id: string,
): DashboardTemplate | undefined =>
  DASHBOARD_TEMPLATES.find(template => template.id === id);

export const filterDashboardTemplates = (
  query: string,
): readonly DashboardTemplate[] => {
  const normalized = query.trim().toLocaleLowerCase();
  if (!normalized) return DASHBOARD_TEMPLATES;

  return DASHBOARD_TEMPLATES.filter(template =>
    [template.title, template.description, ...template.keywords]
      .join(' ')
      .toLocaleLowerCase()
      .includes(normalized),
  );
};
